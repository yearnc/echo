  /// 取一个没被用过的名字。
  ///
  /// [avoid] 里应有：固定住民名、这一帖已经出现的名字、最近用过的名字。
  String next({required Set<String> avoid}) {
    for (var attempt = 0; attempt < 24; attempt++) {
      final candidate = _compose();
      if (!avoid.contains(candidate) && candidate.runes.length <= 8) {
        return candidate;
      }
    }
    // 极端情况下（词库被大量占用）加一个短数字尾巴，保证唯一。
    final base = _compose();
    return '$base${_random.nextInt(90) + 10}';
  }

  String _compose() {
    final roll = _random.nextInt(100);
    if (roll < 42) return _pick(images);
    if (roll < 74) return _pick(casual);
    if (roll < 86) return _pick(platform);
    if (roll < 96) return _pick(latin);
    // 剩下 4%：意象 + 小数字，像很多人真的会加生日/幸运数字。
    return '${_pick(images)}${_random.nextInt(99) + 1}';
  }

  String _pick(List<String> pool) => pool[_random.nextInt(pool.length)];
